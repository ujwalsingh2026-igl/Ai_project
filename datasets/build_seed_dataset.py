def to_sft(rows: list[dict]) -> list[dict]:
    out = []
    for r in rows:
        if r["label"] == "chat":
            target = {"action": "chat"}
        elif r["label"] == "refuse":
            target = {"action": "refuse"}
        else:
            target = {"action": "tool", "tool": r["label"], "args": r["args"]}
        out.append({"messages": [
            {"role": "system", "content": ROUTER_SYSTEM},
            {"role": "user", "content": r["text"]},
            {"role": "assistant", "content": json.dumps(target, ensure_ascii=False)},
        ], "meta": {"id": r["id"], "status": r["status"], "lang": r["lang"]}})
    return out


