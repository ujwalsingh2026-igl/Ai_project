# ---------------------------------------------------------------- helpers
def _typo(s: str) -> str:
    """Swap two adjacent letters inside one longer word (deterministic via RNG)."""
    words = s.split()
    idx = [i for i, w in enumerate(words) if len(w) > 4 and w.isalpha()]
    if not idx:
        return s
    i = RNG.choice(idx)
    w = list(words[i])
    j = RNG.randrange(1, len(w) - 2)
    w[j], w[j + 1] = w[j + 1], w[j]
    words[i] = "".join(w)
    return " ".join(words)


def _voice(s: str) -> str:
    """ASR-style: lowercase, no punctuation."""
    return re.sub(r"[^\w\s']", "", s.lower()).strip()


def _variants(text: str) -> list[tuple[str, str]]:
    seen, out = set(), []
    for kind, v in (("clean", text), ("voice", _voice(text)), ("typo", _typo(text))):
        if v not in seen:
            seen.add(v)
            out.append((kind, v))
    return out


def _expected_decision(label: str) -> str:
    if label == "refuse":
        return "refuse"
    if label == "chat":
        return "none"
    return PermissionEngine().evaluate(
        type("S", (), {"risk_level": TOOLS[label]["risk"], "required_permission": "x.y"})(),
        PermissionContext(user_id=1)).decision.value


def build_intents() -> dict[str, list[dict]]:
    splits = {"train": [], "val": [], "test": []}
    for label, groups in T.items():
        order = list(range(len(groups)))
        RNG.shuffle(order)
        n = len(order)
        n_test = max(1, round(n * 0.15))
        n_val = max(1, round(n * 0.15))
        assign = {}
        for rank, gi in enumerate(order):
            assign[gi] = "test" if rank < n_test else "val" if rank < n_test + n_val else "train"
        for gi, (text, lang, args) in enumerate(groups):
            gid = f"{label}-{gi:02d}"
            for kind, variant in _variants(text):
                splits[assign[gi]].append({
                    "id": hashlib.sha1(f"{gid}|{kind}".encode()).hexdigest()[:12],
                    "group": gid,
                    "text": variant,
                    "variant": kind,
                    "lang": lang,
                    "label": label,
                    "args": args,
                    "status": TOOLS[label]["status"] if label in TOOLS else "implemented",
                    "risk_level": TOOLS[label]["risk"] if label in TOOLS else None,
                    "ownership_confirmation_required": bool(TOOLS.get(label, {}).get("ownership_confirmation")),
                    "expected_decision_default_policy": _expected_decision(label),
                    "source": SOURCE,
                })
    for rows in splits.values():
        RNG.shuffle(rows)
    return splits


def write_jsonl(path: Path, rows: list[dict]) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


